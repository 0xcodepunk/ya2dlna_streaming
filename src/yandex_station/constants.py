from core.enums import AliceState

ALICE_ACTIVE_STATES = frozenset(
    {AliceState.LISTENING, AliceState.SPEAKING, AliceState.BUSY}
)

RUARK_IDLE_VOLUME = 2

# Громкость Ruark на старте сеанса, если устройство стоит на тишине:
# ноль на колонке — не пользовательский выбор, а след приглушения,
# и стрим не должен начинаться в полной тишине
RUARK_MIN_START_VOLUME = 15

RUARK_MAX_VOLUME = 100

# Голосовая громкость: шаг станции на одно «Алиса, громче» или «тише»
# и сколько единиц Ruark (0–100) он меняет. Значение подбирается
# на живой системе; щелчок ручки Ruark — около 3.2 единицы
STATION_VOLUME_STEP = 0.1
RUARK_VOLUME_PER_STATION_STEP = 7

# Ниже этого уровня «Алиса, тише» не опускает Ruark. Граница заметно
# выше RUARK_IDLE_VOLUME: уровень не выше приглушения память громкости
# считает следом речи Алисы и не запоминает
RUARK_MIN_VOICE_VOLUME = 5

FADE_TIME = 1

SOCKET_RECONNECT_DELAY = 1

# Потолок паузы переподключения к станции: пауза удваивается от
# SOCKET_RECONNECT_DELAY до этого значения. Если станция не отвечает
# на соединение (выключена или загружается), задержка до возобновления
# стрима после её возврата не больше этого значения плюс
# STATION_CONNECT_TIMEOUT, секунды
SOCKET_RECONNECT_MAX_DELAY = 30

# Таймаут установки соединения со станцией (TCP и TLS), секунды.
# Станция в локальной сети отвечает за десятки миллисекунд, а
# выключенная не отвечает совсем: без этого таймаута попытка висит
# 30 с по стандарту aiohttp
STATION_CONNECT_TIMEOUT = 5

STREAMING_RESTART_DELAY = 1

# Потолок паузы перезапуска упавшего цикла стриминга: пауза удваивается
# от STREAMING_RESTART_DELAY до этого значения и возвращается к стартовой,
# если цикл проработал без падения дольше STREAMING_FAILURE_STREAK_RESET,
# секунды
STREAMING_RESTART_MAX_DELAY = 30

# Heartbeat цикла стриминга: максимальное ожидание события станции,
# после которого итерация выполняется принудительно, секунды
STREAM_POLL_INTERVAL = 0.5

# Скачок прогресса трека больше этого порога считается разрывом
# (повтор, перемотка) и требует ресинка локального стрима, секунды
PROGRESS_JUMP_THRESHOLD = 5.0

# Страховка от тишины: как часто опрашивать Ruark и сколько ждать
# после отправки потока, прежде чем считать тишину проблемой, секунды
SILENCE_CHECK_INTERVAL = 3.0
SILENCE_RESEND_GRACE = 15.0

# Сколько пересылок потока подряд без звука терпеть, прежде чем
# признать Ruark недоступным и вернуть звук на станцию
SILENT_RESEND_LIMIT = 3

# Кеш прямых ссылок на треки: время жизни записи (CDN-ссылки
# протухают) и максимум записей, секунды / штуки
TRACK_SOURCE_TTL = 600.0
TRACK_SOURCE_CACHE_SIZE = 8

# Локальный TTS: sendText с этим префиксом заставляет Алису
# произнести фразу вслух
TTS_REPEAT_PREFIX = "Повтори за мной"

# Голосовые уведомления об ошибках: сколько падений цикла подряд
# терпеть до объявления и сколько цикл должен проработать без падения,
# чтобы счётчик сбросился, секунды
STREAMING_FAILURE_ANNOUNCE_AFTER = 3
STREAMING_FAILURE_STREAK_RESET = 60.0

# Сколько терпеть недоступность Ruark до голосового объявления, секунды.
# UPnP Ruark зависает на первом потоке и оживает сам: обычно за минуту,
# самое долгое замеренное зависание с перезагрузкой длилось 181 с
RUARK_OUTAGE_PATIENCE = 240.0

# Пауза между попытками достучаться до зависшего Ruark, секунды.
# Постоянная, без роста: Ruark оживает сам, и растущая пауза
# задержала бы подхват ожившей колонки
RUARK_RETRY_INTERVAL = 1
